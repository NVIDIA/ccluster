"""The template every ccluster.nvidia.com/v1alpha1 object is a concrete version of.

The sibling modules of this package (cclcomponentset.py, cclinfraplane.py, ...) are
generated by `make python-generate` from the CRDs and hold each kind's Spec and Status,
the two parts that differ between kinds. This module is hand-written and holds what they
share: the envelope every Kubernetes object carries - apiVersion, kind and metadata - as
the generic CustomResource. The package's __init__.py, also generated, declares one
concrete CustomResource[Spec, Status] per kind and the Kind enum naming them.
"""

from typing import Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field

__all__ = ["API_VERSION", "CustomResource", "ObjectMeta"]

API_VERSION = "ccluster.nvidia.com/v1alpha1"

SpecT = TypeVar("SpecT", bound=BaseModel)
StatusT = TypeVar("StatusT", bound=BaseModel)


class ObjectMeta(BaseModel):
    """The metadata a client sets on an object.

    The API server validates metadata against its built-in ObjectMeta, not the CRD, and
    fills in the fields it manages (uid, resourceVersion, generation, managedFields, ...).
    Those are accepted and kept when an object is read back, but not modelled.
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    name: str | None = None
    namespace: str | None = None
    labels: dict[str, str] | None = None
    annotations: dict[str, str] | None = None


class CustomResource(BaseModel, Generic[SpecT, StatusT]):
    """One object of this API version: the shared envelope around a kind's spec and status.

    A concrete kind is CustomResource[<Kind>Spec, <Kind>Status] with `kind` narrowed to
    that kind's name; see the package's __init__.py.
    """

    model_config = ConfigDict(populate_by_name=True)

    api_version: Literal["ccluster.nvidia.com/v1alpha1"] = Field(API_VERSION, alias="apiVersion")
    kind: str
    metadata: ObjectMeta
    spec: SpecT
    status: StatusT | None = None
