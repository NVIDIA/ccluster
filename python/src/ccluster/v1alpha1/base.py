"""The ccluster.nvidia.com/v1alpha1 objects, assembled from the generated spec and status.

The sibling modules of this package (cclcomponentset.py, cclinfraplane.py) are generated by
`make python-generate` from the CRDs and hold each kind's Spec and Status, the two parts
that differ between kinds. This module is hand-written: it adds the envelope every
Kubernetes object shares - apiVersion, kind and metadata - so a caller can build, apply and
read back a whole object with types. Adding a kind means adding one class here.
"""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from ccluster.v1alpha1.cclcomponentset import CCLComponentSetSpec, CCLComponentSetStatus
from ccluster.v1alpha1.cclinfraplane import CCLInfraPlaneSpec, CCLInfraPlaneStatus

__all__ = ["API_VERSION", "CCLComponentSet", "CCLInfraPlane", "ObjectMeta"]

API_VERSION = "ccluster.nvidia.com/v1alpha1"


class ObjectMeta(BaseModel):
    """The metadata a client sets on an object.

    The API server validates metadata against its built-in ObjectMeta, not the CRD, and
    fills in the fields it manages (uid, resourceVersion, generation, managedFields, ...).
    Those are accepted and kept when an object is read back, but not modelled.
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    name: str | None = None
    namespace: str | None = None
    labels: dict[str, str] | None = None
    annotations: dict[str, str] | None = None


class CCLComponentSet(BaseModel):
    """A bundle of catalog charts rolled out in order onto infra-plane clusters."""

    model_config = ConfigDict(populate_by_name=True)

    api_version: Literal["ccluster.nvidia.com/v1alpha1"] = Field(API_VERSION, alias="apiVersion")
    kind: Literal["CCLComponentSet"] = "CCLComponentSet"
    metadata: ObjectMeta
    spec: CCLComponentSetSpec
    status: CCLComponentSetStatus | None = None


class CCLInfraPlane(BaseModel):
    """An infra-plane cluster registered with the control plane's Argo CD."""

    model_config = ConfigDict(populate_by_name=True)

    api_version: Literal["ccluster.nvidia.com/v1alpha1"] = Field(API_VERSION, alias="apiVersion")
    kind: Literal["CCLInfraPlane"] = "CCLInfraPlane"
    metadata: ObjectMeta
    spec: CCLInfraPlaneSpec
    status: CCLInfraPlaneStatus | None = None
