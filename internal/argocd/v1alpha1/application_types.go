package v1alpha1

import (
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// Health and sync status values the operator compares against. Argo CD defines more of
// each; only the ones the rollout report distinguishes are named here.
const (
	HealthStatusHealthy     = "Healthy"
	HealthStatusProgressing = "Progressing"
	HealthStatusDegraded    = "Degraded"

	SyncStatusSynced = "Synced"
)

// Application is a **read-only** view of an Argo CD Application.
//
// The operator never creates or updates one: Applications are generated by the
// ApplicationSet it writes, and Argo CD owns their whole lifecycle. This type exists so
// CCLDeployment can report which wave of a RollingSync is in flight, which means reading
// health and sync status back off the generated Applications.
//
// Deliberately absent is a Spec field. This type models almost none of an Application,
// and the partial-model hazard documented on ApplicationSet applies here with no
// ownership check to contain it - writing one of these back would strip nearly the whole
// object. Leaving Spec out makes that mistake fail to compile rather than fail in
// production.
//
// +kubebuilder:object:root=true
type Application struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Status ApplicationStatus `json:"status,omitempty"`
}

// ApplicationStatus is the observed state of an Application.
type ApplicationStatus struct {
	// health is Argo CD's assessment of the deployed resources. A RollingSync step
	// does not advance until every Application it selects reports Healthy.
	Health ApplicationHealthStatus `json:"health,omitempty"`

	// sync reports whether the live state matches the source revision.
	Sync ApplicationSyncStatus `json:"sync,omitempty"`
}

// ApplicationHealthStatus is the health half of an Application's status.
type ApplicationHealthStatus struct {
	Status  string `json:"status,omitempty"`
	Message string `json:"message,omitempty"`
}

// ApplicationSyncStatus is the sync half of an Application's status.
type ApplicationSyncStatus struct {
	Status string `json:"status,omitempty"`
}

// ApplicationList contains a list of Application.
//
// +kubebuilder:object:root=true
type ApplicationList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`

	Items []Application `json:"items"`
}

func init() {
	SchemeBuilder.Register(&Application{}, &ApplicationList{})
}
